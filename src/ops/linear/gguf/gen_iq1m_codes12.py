"""Writes ggml_bridge_iq1m_codes.inc: the 12-bit IQ1_M code table of --deepseek-iq1m-codes12.

Entry e (0..4095) is a grid index (the low 11 bits) and a delta sign (bit 11, set for -1/8). It holds
the eight int8 weights 8 c - 7 (sign clear) or 8 c - 9 (set), c the grid's code 0..2 of each value,
as two words: values 0..3 and values 4..7, one per byte, so the kernel reads a group's weights with
one 8-byte load. Derived here from the text of ggml-common.h's iq1s_grid_gpu in plain Python, apart
from the device's SWAR arithmetic (iq1m_tile.h), so that tests/ops/test_iq1m_tile.cpp checks one
against the other.

    python gen_iq1m_codes12.py ../../../../third_party/ggml-quants/src/ggml-common.h ggml_bridge_iq1m_codes.inc
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
start = text.index("GGML_TABLE_BEGIN(uint32_t, iq1s_grid_gpu, NGRID_IQ1S)")
end = text.index("GGML_TABLE_END()", start)
grid = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]{8}", text[start:end])]
assert len(grid) == 2048, len(grid)

words = []
for entry in range(4096):
    g = grid[entry & 2047]
    offset = 9 if entry >> 11 else 7
    for half in range(2):  # values 0..3, then 4..7
        word = 0
        for b in range(4):
            code = (g >> (8 * b + 4 * half)) & 0xF
            assert code <= 2, (entry, code)
            value = 8 * code - offset
            assert -9 <= value <= 9
            word |= (value & 0xFF) << (8 * b)
        words.append(word)

with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by gen_iq1m_codes12.py from ggml-common.h; do not edit.\n")
    out.write("// 4096 entries x 2 words: see that script.\n")
    for i in range(0, len(words), 8):
        out.write("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
